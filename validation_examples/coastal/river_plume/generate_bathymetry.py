#!/usr/bin/env python3
"""Generate synthetic bathymetry for the river plume example.

Creates a NetCDF bathymetry file with:
  - A narrow river channel on the west side (200 m wide, 1000 m long, 4 m deep)
  - Opening into a wider harbour basin (2000 m x 1500 m, 12 m deep)
  - Smooth transition between channel and basin
  - Land (positive elevation) flanking the channel

Grid: 3000 m x 1500 m at 10 m resolution -> 300 x 150 physical cells.

Usage:
    python generate_bathymetry.py [--output bathymetry.nc] [--plot]
"""
import argparse
import numpy as np

try:
    from netCDF4 import Dataset
except ImportError:
    raise SystemExit("netCDF4 required: pip install netCDF4")


def generate_bathymetry(nx=300, ny=150, dx=10.0, dy=10.0):
    """Generate channel + basin bathymetry.

    Returns b(nx, ny) where negative = below sea level (water), positive = land.
    """
    b = np.full((nx, ny), 5.0)  # default: land at +5 m

    # Cell-centre coordinates (m)
    x = (np.arange(nx) + 0.5) * dx  # 5 .. 2995
    y = (np.arange(ny) + 0.5) * dy  # 5 .. 1495

    xx, yy = np.meshgrid(x, y, indexing="ij")  # (nx, ny)

    # Domain geometry
    channel_length = 1000.0   # m from west edge
    channel_width = 200.0     # m
    channel_depth = 4.0       # m below sea level
    basin_depth = 12.0        # m below sea level
    transition_length = 200.0 # m smooth ramp from channel to basin

    y_centre = ny * dy / 2.0  # 750 m
    half_channel = channel_width / 2.0

    # --- Basin (east of channel) ---
    # Full width and depth east of the transition zone
    basin_start = channel_length + transition_length
    basin_mask = xx >= basin_start
    b[basin_mask] = -basin_depth

    # --- Transition zone ---
    # Smooth widening + deepening from channel to basin
    trans_mask = (xx >= channel_length) & (xx < basin_start)
    if np.any(trans_mask):
        # Fraction through transition: 0 at channel end, 1 at basin start
        frac = (xx[trans_mask] - channel_length) / transition_length

        # Channel widens smoothly to full domain width
        half_w = half_channel + frac * (y_centre - half_channel)
        y_dist = np.abs(yy[trans_mask] - y_centre)
        in_water = y_dist <= half_w

        # Depth ramps from channel_depth to basin_depth
        depth = channel_depth + frac * (basin_depth - channel_depth)
        b[trans_mask] = np.where(in_water, -depth, 5.0)

    # --- River channel ---
    channel_mask = (xx < channel_length) & \
                   (np.abs(yy - y_centre) <= half_channel)
    b[channel_mask] = -channel_depth

    # --- Smooth channel edges ---
    # Apply a gentle slope at channel walls (over ~2 cells) to avoid
    # sharp bathymetric steps that stress the BPG
    edge_width = 2.0 * dy  # 20 m smoothing zone
    for ix in range(nx):
        if x[ix] >= basin_start:
            continue
        for iy in range(ny):
            if b[ix, iy] > 0:  # land cell
                y_dist = abs(y[iy] - y_centre)
                if x[ix] < channel_length:
                    edge = half_channel
                else:
                    frac = (x[ix] - channel_length) / transition_length
                    edge = half_channel + frac * (y_centre - half_channel)

                overshoot = y_dist - edge
                if 0 < overshoot < edge_width:
                    # Smooth ramp from water to land
                    alpha = overshoot / edge_width
                    local_depth = channel_depth if x[ix] < channel_length else \
                        channel_depth + (x[ix] - channel_length) / transition_length * (basin_depth - channel_depth)
                    b[ix, iy] = -local_depth * (1.0 - alpha) + 5.0 * alpha

    return b


def write_netcdf(filename, b, dx, dy):
    """Write bathymetry to NetCDF file."""
    nx, ny = b.shape
    ds = Dataset(filename, "w", format="NETCDF4")

    ds.createDimension("x", nx)
    ds.createDimension("y", ny)

    bvar = ds.createVariable("b", "f8", ("x", "y"))
    bvar.long_name = "bottom elevation"
    bvar.units = "m"
    bvar.positive = "up"
    bvar[:] = b

    xvar = ds.createVariable("x", "f8", ("x",))
    xvar.long_name = "x-coordinate"
    xvar.units = "m"
    xvar[:] = (np.arange(nx) + 0.5) * dx

    yvar = ds.createVariable("y", "f8", ("y",))
    yvar.long_name = "y-coordinate"
    yvar.units = "m"
    yvar[:] = (np.arange(ny) + 0.5) * dy

    ds.title = "Synthetic river plume bathymetry"
    ds.description = (
        "River channel (200m wide, 4m deep, 1000m long) opening into "
        "harbour basin (2000m x 1500m, 12m deep). Generated by "
        "generate_bathymetry.py"
    )
    ds.dx = dx
    ds.dy = dy

    ds.close()
    print(f"Wrote {filename}: {nx} x {ny}, "
          f"depth range [{b.min():.1f}, {b.max():.1f}] m")


def plot_bathymetry(b, dx, dy):
    """Quick plot of the bathymetry."""
    import matplotlib.pyplot as plt

    nx, ny = b.shape
    x = np.arange(nx + 1) * dx
    y = np.arange(ny + 1) * dy

    fig, ax = plt.subplots(1, 1, figsize=(12, 5))
    pcm = ax.pcolormesh(x, y, b.T, cmap="terrain", vmin=-15, vmax=5)
    ax.set_xlabel("x (m)")
    ax.set_ylabel("y (m)")
    ax.set_title("River Plume Bathymetry")
    ax.set_aspect("equal")
    fig.colorbar(pcm, ax=ax, label="Elevation (m)")

    # Mark the channel and basin
    ax.axvline(1000, color="white", ls="--", lw=0.5, label="channel end")
    ax.axvline(1200, color="white", ls=":", lw=0.5, label="basin start")
    ax.legend(loc="upper right", fontsize=8)

    plt.tight_layout()
    plt.savefig("bathymetry.png", dpi=150)
    print("Saved bathymetry.png")
    plt.show()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default="bathymetry.nc",
                        help="Output NetCDF file (default: bathymetry.nc)")
    parser.add_argument("--plot", action="store_true",
                        help="Show bathymetry plot")
    args = parser.parse_args()

    dx, dy = 10.0, 10.0
    b = generate_bathymetry(nx=300, ny=150, dx=dx, dy=dy)
    write_netcdf(args.output, b, dx, dy)

    if args.plot:
        plot_bathymetry(b, dx, dy)
